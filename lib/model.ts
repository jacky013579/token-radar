// Token Radar model v2: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every protocol that (a) records no token and (b) passes the
// watchlist's own cleanliness rule, whatever its TVL: the 40 watchlist protocols
// plus every clean pre-token protocol below the $50M floor. A protocol above the
// floor that the watchlist leaves out is not ranked: the snapshot carries no
// parent-protocol field, so the entry cannot verify it is not a wrapped, staked
// or bridged product of something that already trades, and it says so instead
// of guessing. Wrapped, staked and bridged products, versioned pools (a name
// ending in V2 / 2.0) and exchanges are excluded everywhere, for the same
// reason: WBTC is Bitcoin on Ethereum, not a protocol waiting on a launch.
//
// Implied value is an estimated fully-diluted value at launch, priced like the
// protocol's live peers rather than from a flat multiple. For each category the
// model takes the median market-cap/TVL ratio of the snapshot's live-token
// protocols in that category, shrinks it toward the global median (a category
// with two live comps does not get to claim a 400x multiple), and clamps it to
// [0.05, 0.50]. Then:
//
//   implied = round( tvl_usd x category_multiple
//                    x (1 + clamp(change_7d, -60, 120) / 100 x 0.5)
//                    x (0.6 + min(age_days, 1095) / 1095 x 0.4)
//                    x (1 + min(chains - 1, 3) x 0.03) )
//
// TVL, growth and age come from the snapshot; the category multiple is computed
// from the snapshot's live protocols at run time, so the same program scores a
// future snapshot with no hand-kept list of names. No protocol name is ever
// special-cased: the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

